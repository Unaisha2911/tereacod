/**
 * TereaCOD — product_ratings TABLE-ONLY creator for remote D1.
 *
 * For a live remote D1 whose catalog was authored in the admin console
 * (products differ from the local seed and ratings are managed there too),
 * the ONLY thing migration 0008 adds that the storefront and admin need is
 * the `product_ratings` TABLE itself. This script emits exactly that —
 * verbatim from migrations/0008_product_ratings.sql — and nothing else:
 *
 *   • NO rating rows are inserted (no seed data, no slug matching);
 *   • NO other table is read, written, or dropped;
 *   • idempotent `CREATE TABLE IF NOT EXISTS` — safe to re-run.
 *
 * Once the table exists remotely, ratings are authored per product in the
 * admin console (product editor) — unrated products simply render unrated.
 *
 * Usage:
 *   bun run db:ratings:table          # generate scripts/ratings-table.sql (inspect first)
 *   bun run db:ratings:table:remote   # generate + apply to remote D1
 */

import { writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const OUT_SQL = path.join(ROOT, "scripts", "ratings-table.sql");

const now = new Date().toISOString();
const lines: string[] = [];
lines.push(`-- TereaCOD — product_ratings TABLE-ONLY creation (generated by scripts/ratings-table.ts)`);
lines.push(`-- Generated: ${now}`);
lines.push(`-- DDL is verbatim from migrations/0008_product_ratings.sql.`);
lines.push(`-- No rating rows are inserted — ratings are authored in the admin console.`);
lines.push(`-- Idempotent: safe to re-run on a remote that already has the table.`);
lines.push(``);

lines.push(`CREATE TABLE IF NOT EXISTS product_ratings (`);
lines.push(`  product_id   TEXT PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,`);
lines.push(`  rating_value REAL    NOT NULL CHECK (rating_value >= 0.5 AND rating_value <= 5),`);
lines.push(`  rating_count INTEGER NOT NULL CHECK (rating_count >= 1),`);
lines.push(`  updated_at   TEXT    NOT NULL`);
lines.push(`);`);
lines.push(``);

writeFileSync(OUT_SQL, lines.join("\n"), { mode: 0o600 });

console.log("✓ product_ratings table-only SQL generated (no rows, no seed data)");
console.log(`→ ${path.relative(ROOT, OUT_SQL)}`);
console.log("");
console.log("Next:");
console.log("  bun run db:ratings:table:remote   # create the table on remote D1 (idempotent)");
